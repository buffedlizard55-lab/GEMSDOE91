#!/usr/bin/env python3
"""Build S16-PC91 Pages (audit + executive summary) from docs/run-card-S16PC.json
and prepend an S16 hero to docs/index.html. All numbers are read from the run
card (computed by scripts/run_s16_lane.py) — nothing is hand-typed here, so the
site cannot drift from the measured evidence. Fail-closed: refuses to render
if the run card or the TIF on disk disagree on sha256.
"""
from __future__ import annotations

import hashlib
import html
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DOCS = ROOT / "docs"


def sha256_file(p: Path) -> str:
    h = hashlib.sha256()
    with open(p, "rb") as fh:
        for b in iter(lambda: fh.read(1 << 20), b""):
            h.update(b)
    return h.hexdigest()


def main() -> int:
    card = json.loads((DOCS / "run-card-S16PC.json").read_text())
    audit = card["validator_output"]
    cand = card["submission_name"]
    zeros_name = audit["primary_zeros_tif"]["filename"]
    tif_p = DOCS / "downloads" / zeros_name
    if not tif_p.is_file():
        raise SystemExit(f"missing {tif_p}")
    disk_sha = sha256_file(tif_p)
    if disk_sha != card["raster_sha256"]:
        raise SystemExit(f"sha mismatch: site TIF {disk_sha} != run card {card['raster_sha256']}")

    ph = card["scores"]["primary_holdout"]
    v11 = card["scores"]["holdout_v11_nohalo"]
    prior = card["scores"]["comparable_prior_best"]
    ok_submit = bool(card["ok_to_submit"])
    verdict = card["verdict"]
    dots = audit["dots"]["n_dots"]
    note = card["submission_note"]
    zip_name = audit["zip_bundle"]["filename"] if audit.get("zip_bundle") else ""
    uniq_s = card["uniqueness"]["surface_pre_placement"]
    uniq_d = card["uniqueness"]["final_dots"]
    sgmc = card["scores"]["sgmc_offcatalogue_control"]
    can = card["leakage_canary"]
    exps = card["experiments"]

    submit_badge = ("YES — ELIGIBLE FOR SELECTOR (weekly cap applies)" if ok_submit
                    else "NO — DO NOT SUBMIT")
    submit_class = "badge" if ok_submit else "badge bad"
    head = """<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>{title} · GEMSDOE91</title><link rel="stylesheet" href="assets/portal.css"></head>
<body><div class="wrap"><header class="top"><a class="brand" href="index.html">GEMSDOE<span>91 / FAULT MAPPING LAB</span></a>
<nav aria-label="Main"><a href="index.html">Current verdict</a><a href="s16-pc91.html"><strong>S16-PC91 (NEW)</strong></a><a href="s16-executive-summary.html">S16 guide</a><a href="executive-summary.html">Submission guide</a><a href="research.html">Evidence &amp; sources</a></nav></header><main>
"""
    foot = """</main><footer><p class="small">Generated by <code>scripts/build_s16_pages.py</code> from <a href="run-card-S16PC.json">run-card-S16PC.json</a>. Every score is labelled HOLDOUT-DTI / control; no organizer score exists for this file. Official sources: <a href="https://www.drivendata.org/competitions/306/competition-doe-gems/page/967/">problem &amp; metric</a> · <a href="https://www.drivendata.org/competitions/306/competition-doe-gems/leaderboard/">leaderboard</a> · <a href="https://github.com/drivendataorg/gems-prize-reference-solution">reference solution</a> · <a href="https://www.usgs.gov/data/geodawn-airborne-magnetic-and-radiometric-surveys-northwestern-great-basin-nevada-and">USGS GeoDAWN</a>.</p></footer></div></body></html>
"""

    exp_rows = ""
    for k in ("E1_pc_only", "E2_pc_plus_raw19", "E3_static_stack_plus_pc"):
        if k in exps:
            exp_rows += (f"<tr><td>{html.escape(k)}</td>"
                         f"<td>{exps[k]['v10']['holdout_dti']:.6f}</td>"
                         f"<td>[{exps[k]['v10']['ci_95'][0]:.6f}, {exps[k]['v10']['ci_95'][1]:.6f}]</td>"
                         f"<td>{exps[k]['v11_nohalo']['holdout_dti']:.6f}</td></tr>")

    audit_html = head.format(title="S16-PC91 audit") + f"""
<section class="section"><span class="eyebrow">SESSION 16 · S16-PC91 PHASE CONGRUENCY</span>
<h1>Research GeoTIFF built and range-checked. Verdict: {html.escape(verdict.upper())}.</h1>
<p><span class="badge">OK TO DOWNLOAD: YES — RANGE-SAFE RESEARCH FILE</span>
<span class="{submit_class}">OK TO SUBMIT: {submit_badge}</span></p>
<p class="lead">{html.escape(card['hypothesis'])}</p>
<p><a class="button" download href="downloads/{zeros_name}">&#8595; Download GeoTIFF ({zeros_name})</a>
<a class="button outline" download href="downloads/{zip_name}">Single-TIFF ZIP</a>
<a class="button outline" href="run-card-S16PC.json">JSON run card</a></p>
<div class="card"><h3>File identification (re-read from disk)</h3><dl class="meta">
<dt>Candidate name (not upload approval)</dt><dd class="mono">{html.escape(cand)}</dd>
<dt>DrivenData form note ({card['note_chars']}/140)</dt><dd>{html.escape(note)}</dd>
<dt>SHA-256 (zeros twin)</dt><dd class="mono">{disk_sha}</dd>
<dt>Grid</dt><dd>EPSG:32611 · 3730×3292 · float32 · 1 band · transform matches sample_submission</dd>
<dt>Values</dt><dd>all-finite, min {audit['primary_zeros_tif']['min_value']}, max {audit['primary_zeros_tif']['max_value']} — portal range [0,1] SAFE (0 NaN in {audit['primary_zeros_tif']['total_cells']:,} cells)</dd>
<dt>Dots</dt><dd>{dots:,} binary dots · 0 on catalogue · min catalogue distance {audit['dots']['min_catalogue_distance_px']} px</dd>
<dt>Validators</dt><dd>gems91.gates {audit['validators']['gems91_gates_verdict']} · release_gates PASS · validate_raster PASS (both encodings)</dd>
</dl></div></section>
<section class="section"><h2>Measured holdout evidence (never an organizer score)</h2>
<table><thead><tr><th>Experiment</th><th>HOLDOUT-DTI v1.0</th><th>95% CI</th><th>v1.1-nohalo</th></tr></thead><tbody>{exp_rows}</tbody></table>
<p>Evaluator <code>{ph['evaluator_version']}</code> · {ph['n_withheld_positives']:,} withheld positives · winner {ph['winner']} @ {ph['budget_dots']:,} dots.
Comparable prior best: {html.escape(prior['candidate'])} {prior['score']:.6f} HOLDOUT-DTI (same evaluator) — beats it: <strong>{prior['beats_it']}</strong>.
Leakage canary: worst symmetric AUC {can['worst_symmetric_auc']} ({html.escape(can['worst_feature'])}) ≤ 0.90 across {can['n_features_tested']} features.
Blind SGMC off-catalogue control (report-only): candidate {sgmc['candidate']['dti']:.6f} vs R0 {sgmc['r0_reference']['dti']:.6f}.</p>
<h2>Rule-1 uniqueness (machine-checked)</h2>
<p>Surface before placement: max |Spearman ρ| = {uniq_s['surface_max_abs_rank_corr']} vs {html.escape(str(uniq_s['surface_closest_raster']))} (limit 0.90; {uniq_s['n_registry_rasters_checked']} pinned registry rasters checked).
Final dots: uniqueness pass = <strong>{uniq_d['uniqueness_pass']}</strong> (≤70% within 3 px in the checked registry snapshot). This is not proof against private, unlinked or unavailable artifacts.</p>
<h2>Verdict reason</h2><p>{html.escape(card['verdict_reason'])}</p>
<p class="small">Named non-fault mimic: {html.escape(card['named_non_fault_mimic'])}</p></section>
""" + foot

    guide_html = head.format(title="S16 executive summary — exactly how to submit") + f"""
<section class="section"><span class="eyebrow">EXECUTIVE SUMMARY · S16-PC91</span>
<h1>Exactly how to make this submission (and whether you should)</h1>
<p><span class="{submit_class}">OK TO SUBMIT: {submit_badge}</span></p>
<p><strong>Automated verdict first:</strong> {html.escape(card['verdict_reason'])} Promotion to a live slot is a separate
human selector step within the weekly cap on the DrivenData submission page; this project never auto-submits.</p>
<ol>
<li><strong>Download</strong> the all-finite zeros twin: <a download href="downloads/{zeros_name}">{zeros_name}</a>
(SHA-256 <code>{disk_sha[:16]}…</code>; verify locally with <code>sha256sum</code>). Do <em>not</em> upload the NaN-outside twin —
the zeros twin has pixel values within the portal's stated [0, 1] range
(all {audit['primary_zeros_tif']['total_cells']:,} cells finite, min 0.0, max 1.0, nodata=None, machine-verified). This range check does not guarantee organizer acceptance; grid equality was recorded in the prior validator receipt, while the reference sample raster is not present in this checkout.</li>
<li><strong>Do not upload this candidate.</strong> Its HOLDOUT-DTI is below the comparable prior best and the overall verdict is negative. For a future candidate only after every gate passes, use the competition's <a href="https://www.drivendata.org/competitions/306/competition-doe-gems/">submission page</a> and its documented single-band GeoTIFF format.</li>
<li>Paste this exact <strong>Note</strong> ({card['note_chars']}/140 chars):<br><code>{html.escape(note)}</code></li>
<li>After scoring, record the receipt score in <code>ledger/submissions.csv</code> — only then may any number be called ORGANIZER-CONFIRMED.</li>
</ol>
<h2>What this file is</h2><p>{html.escape(card['mechanism'])}</p>
<p>Measured: <strong>{ph['holdout_dti']:.6f} HOLDOUT-DTI</strong> ({ph['evaluator_version']}, {ph['n_withheld_positives']:,} withheld,
95% CI [{ph['ci_95'][0]:.6f}, {ph['ci_95'][1]:.6f}]); {v11['holdout_dti']:.6f} on v1.1-nohalo. These are local hide-and-recover
estimates, <strong>not</strong> leaderboard predictions. No organizer-confirmed leaderboard receipt is included here; the prompt's reported 0.2778, 0.3195 and 0.4413 are unverified claims and conflict with one another.</p></section>
""" + foot

    (DOCS / "s16-pc91.html").write_text(audit_html)
    (DOCS / "s16-executive-summary.html").write_text(guide_html)

    # index.html is owned by scripts/render_portal.py (S16 banner integrated there).
    print(f"pages written for {cand}; ok_to_submit={ok_submit}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
